"""Runs the whole experiment and writes results.md.

    python experiment.py           # full run (a few minutes on a laptop CPU)
    python experiment.py --quick   # small run used in CI
"""

import argparse
import time
from pathlib import Path

import numpy as np
import torch

from dda.agent import TrainConfig, dqn_policy, evaluate, random_policy, train_dqn
from dda.difficulty import Director, collect, scores, simulate, split_by_player, train_baseline, train_win_model
from dda.env import GemRun, LevelConfig, generate_level
from dda.player import SimulatedPlayer, random_players

TRAIN_LEVELS = [LevelConfig(s, t) for s in (5, 6, 7) for t in (0.05, 0.15, 0.25, 0.3)]
TEST_LEVELS = {"easy (5x5, 5% traps)": LevelConfig(5, 0.05), "medium (6x6, 15%)": LevelConfig(6, 0.15), "hard (7x7, 30%)": LevelConfig(7, 0.30)}
TIERS = {"lower skill (0.50-0.65)": (0.5, 0.65), "middle skill (0.65-0.80)": (0.65, 0.8), "higher skill (0.80-0.95)": (0.8, 0.96)}


def planner_policy(game: GemRun, obs, rng) -> int:
    """Upper bound: a player with perfect skill who heads straight for the exit."""
    player = SimulatedPlayer(-1, skill=1.0)
    return player._choose(game, 0, rng)


def table(header: list[str], rows: list[list[str]]) -> str:
    lines = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    lines += ["| " + " | ".join(r) + " |" for r in rows]
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--quick", action="store_true")
    args = parser.parse_args()
    q = args.quick
    torch.set_num_threads(1)
    out: list[str] = ["# Results", "", f"Generated by `python experiment.py{' --quick' if q else ''}`. Every number below comes from that run.", ""]

    # 1. Reinforcement learning agent
    started = time.time()
    episodes = 600 if q else 5000
    net, rewards = train_dqn(TRAIN_LEVELS, TrainConfig(episodes=episodes), seed=1, log_every=0 if q else 500)
    minutes = (time.time() - started) / 60
    if not q:
        Path("models").mkdir(exist_ok=True)
        torch.save(net.state_dict(), "models/dqn.pt")
    n_eval = 100 if q else 500
    rows = []
    for name, config in TEST_LEVELS.items():
        r = evaluate(random_policy, config, n_eval, seed=7)
        d = evaluate(dqn_policy(net), config, n_eval, seed=7)
        p = evaluate(planner_policy, config, n_eval, seed=7)
        rows.append([name, f"{r['win_rate']:.0%}", f"**{d['win_rate']:.0%}**", f"{d['trap_rate']:.0%}", f"{d['avg_gems']:.2f}", f"{p['win_rate']:.0%}"])
    out += [
        "## 1. Double DQN agent",
        "",
        f"Trained for {episodes} episodes on randomly generated levels ({minutes:.1f} min on CPU). "
        f"Mean episode reward rose from {np.mean(rewards[:100]):.2f} (first 100) to {np.mean(rewards[-100:]):.2f} (last 100). "
        f"Evaluated on {n_eval} new levels per row, all policies on the same levels.",
        "",
        table(["Level", "Random win", "DQN win", "DQN trap", "DQN gems", "Planner win"], rows),
        "",
        "Planner = shortest safe path with full knowledge of the map. It is the upper bound; the agent only sees a 5x5 window.",
        "",
    ]

    # 2. Win prediction from player data
    rng = np.random.default_rng(3)
    players = random_players(120 if q else 400, rng)
    x, y, owners = collect(players, 15 if q else 25, rng)
    test = split_by_player(owners, 0.25, rng)
    model = train_win_model(x[~test], y[~test], epochs=150 if q else 400)
    baseline = train_baseline(x[~test], y[~test])
    m, b = scores(y[test], model.predict(x[test])), scores(y[test], baseline.predict_proba(x[test])[:, 1])
    constant = scores(y[test], np.full(test.sum(), y[~test].mean()))
    out += [
        "## 2. Predicting whether a player wins a level",
        "",
        f"{len(players)} simulated players with different skill and play styles produced {len(y)} sessions "
        f"(overall win rate {y.mean():.0%}). The split is by player: test players never appear in training.",
        "",
        table(
            ["Model", "ROC-AUC (higher is better)", "Log loss (lower)", "Brier (lower)"],
            [
                ["Always predict the average", f"{constant['roc_auc']:.3f}", f"{constant['log_loss']:.3f}", f"{constant['brier']:.3f}"],
                ["Logistic regression (scikit-learn)", f"{b['roc_auc']:.3f}", f"{b['log_loss']:.3f}", f"{b['brier']:.3f}"],
                ["Neural network (PyTorch)", f"{m['roc_auc']:.3f}", f"{m['log_loss']:.3f}", f"{m['brier']:.3f}"],
            ],
        ),
        "",
    ]

    # 3. Dynamic difficulty adjustment
    new_players = random_players(60 if q else 200, np.random.default_rng(11), first_id=10_000)
    target = 0.7
    director = Director(model.predict, target=target)
    fixed = simulate(new_players, 20 if q else 30, lambda h: LevelConfig(6, 0.2), np.random.default_rng(12))
    adaptive = simulate(new_players, 20 if q else 30, director.next_level, np.random.default_rng(12))
    rows = []
    for name, (lo, hi) in TIERS.items():
        ids = [p.player_id for p in new_players if lo <= p.skill < hi]
        rows.append([name, str(len(ids)), f"{np.mean([fixed[i] for i in ids]):.0%}", f"**{np.mean([adaptive[i] for i in ids]):.0%}**"])
    gap_fixed = np.mean([abs(v - target) for v in fixed.values()])
    gap_adaptive = np.mean([abs(v - target) for v in adaptive.values()])
    rows.append(["mean distance from target", "", f"{gap_fixed:.2f}", f"**{gap_adaptive:.2f}**"])
    out += [
        "## 3. Dynamic difficulty",
        "",
        f"{len(new_players)} new players each play {20 if q else 30} levels. Target win rate: {target:.0%}. "
        "Fixed = every level is 6x6 with 20% traps. Adaptive = before each level the director picks the board size "
        "(4 to 8) and trap ratio (0% to 40%) whose predicted win chance for this player is closest to the target, "
        "using the PyTorch win model.",
        "",
        table(["Players", "Count", "Fixed difficulty win rate", "Adaptive win rate"], rows),
        "",
    ]

    # Example game
    game = GemRun(generate_level(LevelConfig(6, 0.2), np.random.default_rng(5)))
    obs, done, frames = game.reset(), False, [game.render()]
    policy = dqn_policy(net)
    while not done:
        obs, _, done, info = game.step(policy(game, obs, None))
        frames.append(game.render())
    out += ["## Example: the trained agent on a new level", "", f"Outcome: **{info['outcome']}**, {game.steps} steps, {game.gems_collected} gems. `@` agent, `x` trap, `*` gem, `E` exit.", "", "```", frames[0], "", frames[-1], "```", ""]

    text = "\n".join(out)
    Path("results-quick.md" if q else "results.md").write_text(text, encoding="utf-8")
    print(text)


if __name__ == "__main__":
    main()
